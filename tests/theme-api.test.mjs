import fs from 'node:fs';
import assert from 'node:assert/strict';
import {pathToFileURL,fileURLToPath} from 'node:url';
const skill=fileURLToPath(new URL('../skills/inkwave-game-ui',import.meta.url));
const {applyInkTheme,setInkPalette,contrastRatio,inkPalettes}=await import(pathToFileURL(skill+'/assets/web/inkwave-ui.mjs'));
const profile=JSON.parse(fs.readFileSync(skill+'/assets/theme-profile.example.json','utf8'));
const props=new Map();
const root={style:{setProperty:(k,v)=>props.set(k,v),removeProperty:k=>props.delete(k)}};
applyInkTheme(root,profile);
assert.equal(props.get('--ink-surface'),profile.colors.surface);
assert.equal(props.get('--ink-action'),profile.colors.action);
assert.equal(props.get('--ink-focus-ms'),'200ms');
assert.equal(props.get('--ink-focus-scale'),'1.012');
assert.equal(props.get('--ink-enter-offset'),'12px');
for(const [key,color] of [['a',profile.colors.primary],['b',profile.colors.secondary],['action',profile.colors.action],['danger',profile.colors.danger]])assert.ok(contrastRatio(color,props.get(`--ink-${key}-on`))>=4.5);
for(const surface of [profile.colors.surface,profile.colors.surfaceAlt])for(const text of [profile.colors.text,profile.colors.muted])assert.ok(contrastRatio(surface,text)>=4.5);
assert.ok(contrastRatio(profile.colors.focus,profile.colors.surface)>=3);
const snapshot=JSON.stringify([...props]);
for(const bad of [{...profile,colors:{...profile.colors,danger:'pink'}},{...profile,motion:{focusMs:NaN}},{...profile,motion:{spring:[2,1,.6,1]}}]){assert.throws(()=>applyInkTheme(root,bad));assert.equal(JSON.stringify([...props]),snapshot);}
assert.throws(()=>setInkPalette(root,'#a37ce7','invalid'));
assert.equal(JSON.stringify([...props]),snapshot);
setInkPalette(root,'#a37ce7','#7fd7d2');
assert.ok(!inkPalettes.some(([a,b])=>a==='#a37ce7'&&b==='#7fd7d2'));
assert.equal(props.get('--ink-a'),'#a37ce7');
assert.equal(props.get('--ink-action'),profile.colors.action);
assert.ok(contrastRatio('#a37ce7',props.get('--ink-a-on'))>=4.5);
applyInkTheme(root,{colors:profile.colors});
assert.equal(props.has('--ink-focus-ms'),false);
assert.equal(props.has('--ink-spring'),false);
console.log('PASS: full role colors, context motion, custom non-source palette, foreground contrast, invalid-input atomicity, optional-motion reset.');
